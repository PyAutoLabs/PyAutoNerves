def check_jax_using_gpu(log_gpu_warning: bool = True) -> bool:
    """
    Report the devices JAX sees and return True if no GPU / TPU is available.

    Considers every device (not just the last one enumerated); an empty device
    list counts as no accelerator.
    """
    import jax

    devices = jax.devices()

    has_accelerator = False

    for d in devices:
        kind = str(d).lower()

        if "gpu" in kind or "cuda" in kind:
            print(f"GPU / CUDA detected: {d}")
            has_accelerator = True
        elif "tpu" in kind:
            print(f"TPU detected: {d}")
            has_accelerator = True
        elif "cpu" in kind:
            print(f"CPU detected: {d}")
        else:
            print(f"Other device detected: {d}")

    no_gpu = not has_accelerator

    if no_gpu and log_gpu_warning:

        logger.info(
            """
            JAX did not detect a GPU or TPU device and is using the CPU for computations.

            PyAuto runs significantly faster with a GPU, so it is recommended to reinstall
            JAX with GPU support, if you have a GPU available, by following the JAX
            installation instructions.
            """
        )

    return no_gpu


#: The JAX floor (PyAutoNerves#215): jax 0.11.x can freeze XLA:CPU likelihoods,
#: and Colab ships an older jax. The package install below is ``--no-deps``,
#: so it would never upgrade jax by itself; :func:`_ensure_jax_floor` does.
_JAX_FLOOR = (0, 12, 0)
_NUMPY_FLOOR = (2, 2, 0)  # jax 0.12 requires numpy>=2.2
_JAX_SPECS = ["jax>=0.12.0,<0.13", "jaxlib>=0.12.0,<0.13"]
_NUMPY_SPEC = "numpy>=2.2"


class ColabRestartRequired(RuntimeError):
    """Raised after upgrading a package (jax or NumPy) this kernel had already loaded."""


def _version_tuple(text):
    parts = []
    for piece in str(text).split(".")[:3]:
        digits = "".join(ch for ch in piece if ch.isdigit())
        parts.append(int(digits) if digits else 0)
    return tuple(parts + [0] * (3 - len(parts)))


def _dist_version(name: str):
    try:
        from importlib.metadata import version

        return version(name)
    except Exception:
        return None


def _ensure_jax_floor() -> None:
    """
    Upgrade Colab's preinstalled jax / jaxlib / NumPy to the supported range.

    Versions are read from package metadata, never by importing jax. Only what is
    below the floor is upgraded: jax and jaxlib together (plus the matching CUDA
    plugin on a GPU runtime), NumPy only if it is older than 2.2.

    A package already imported into the kernel cannot be replaced in place, so
    :class:`ColabRestartRequired` is raised only when an UPGRADED package is
    already loaded. Importing this module loads NumPy but not jax, so on a
    Colab whose NumPy already meets the floor the upgrade completes without a
    restart (PyAutoNerves#217). Otherwise the user restarts once and re-runs the
    setup cell, and on that second run the floor is met.
    """
    import subprocess

    jax_v, jaxlib_v, numpy_v = (_dist_version(n) for n in ("jax", "jaxlib", "numpy"))
    jax_old = (
        jax_v is None
        or jaxlib_v is None
        or _version_tuple(jax_v) < _JAX_FLOOR
        or _version_tuple(jaxlib_v) < _JAX_FLOOR
    )
    numpy_old = numpy_v is None or _version_tuple(numpy_v) < _NUMPY_FLOOR
    if not (jax_old or numpy_old):
        return

    specs, upgraded = [], []
    if jax_old:
        specs += _JAX_SPECS
        upgraded += ["jax", "jaxlib"]
        # A GPU runtime carries a CUDA plugin that must match jaxlib exactly.
        for cuda in ("cuda12", "cuda13"):
            if _dist_version(f"jax-{cuda}-plugin") is not None:
                specs += [
                    f"jax-{cuda}-plugin[with-cuda]>=0.12.0,<0.13",
                    f"jax-{cuda}-pjrt>=0.12.0,<0.13",
                ]
    if numpy_old:
        specs.append(_NUMPY_SPEC)
        upgraded.append("numpy")

    what = " and ".join(n for n, old in (("JAX", jax_old), ("NumPy", numpy_old)) if old)
    print(
        f"Upgrading {what} for PyAuto (found jax {jax_v}, jaxlib {jaxlib_v}, "
        f"numpy {numpy_v}; PyAuto needs jax 0.12 and numpy 2.2 or newer)."
    )
    subprocess.check_call([sys.executable, "-m", "pip", "install", *specs])

    loaded = [name for name in upgraded if name in sys.modules]
    if loaded:
        raise ColabRestartRequired(
            f"{', '.join(loaded)} was upgraded but is already loaded in this "
            "runtime. Restart the runtime (Runtime > Restart session) and run "
            "this setup cell again."
        )


def _running_in_ipython() -> bool:
    """
    True only when an IPython interactive shell (Jupyter notebook, IPython
    kernel or terminal) is driving this process.

    A notebook has already imported IPython by the time any cell runs, so a
    ``sys.modules`` lookup distinguishes the notebook path from a plain
    interpreter without importing IPython (which may be installed but idle)
    on every CLI run.
    """
    ipython = sys.modules.get("IPython")

    if ipython is None:
        return False

    try:
        return ipython.get_ipython() is not None
    except AttributeError:
        return False


def _installed_version(top_package: str):
    """The installed version string of ``top_package``, or None if unknown."""
    try:
        from importlib.metadata import version

        return version(top_package)
    except Exception:
        return None


def _clone_workspace(workspace_repo: str, workspace_dir: str, top_package: str) -> None:
    """
    Shallow-clone the workspace, preferring the tag matching the installed
    release of ``top_package`` so the cloned configs / datasets match the
    pip-installed code; fall back to the default branch when no such tag
    exists (e.g. a dev install).
    """
    import subprocess

    if Path(workspace_dir).exists():
        print("Workspace already exists so not cloning again.")
        return

    tag = _installed_version(top_package)

    if tag is not None:
        result = subprocess.run(
            ["git", "clone", "--depth", "1", "--branch", tag, workspace_repo, workspace_dir]
        )
        if result.returncode == 0:
            return
        print(f"No workspace tag '{tag}' found; cloning the default branch instead.")

    subprocess.run(
        ["git", "clone", "--depth", "1", workspace_repo, workspace_dir], check=True
    )


def _gpu_error_message(project: str, spec: dict) -> str:
    return f"""
    No GPU detected in Google Colab. {spec["project_name"]} runs {spec["gpu_note"]} with a GPU,
    so switch GPU on in Colab settings.

    To do this:

    - Click "Runtime" in the top menu.
    - Click "Change runtime type".
    - Under "Hardware accelerator", select one of the "GPU" options available.

    You can set up Colab with a CPU (e.g. if GPUs are unavailable) by calling:

        setup_colab.setup("{project}", raise_error_if_not_gpu=False)
    """


def _install_arcticpy() -> None:
    """Build arcticpy on Colab by running PyAutoHeart's installer script."""
    import os
    import subprocess
    import sys

    env = dict(os.environ, ARCTICPY_SUDO="false", PYTHON=sys.executable)
    subprocess.check_call(
        ["bash", "-c", f'curl -fsSL "{_ARCTICPY_INSTALLER_URL}" | bash'], env=env
    )


_PRE_INSTALLERS = {"arcticpy": _install_arcticpy}


def _colab_setup(
    *,
    project_name: str,
    workspace_repo: str,
    workspace_dir: str,
    packages: list,
    top_package: str,
    raise_error_if_not_gpu: bool,
    gpu_error_message: str,
    pre_install: str = None,
) -> None:
    """
    Shared Google Colab setup for the PyAuto ecosystem.

    A no-op (bar a short message) when not running inside Google Colab.
    """
    import os
    import subprocess
    import sys

    try:
        import google.colab  # noqa: F401
    except ImportError:
        message = f"""
            You are not running in a Google Colab environment so cannot use the setup_colab() function.

            You should therefore have {project_name} installed locally in your environment already (e.g. via pip or
            conda) and can run the rest of your script normally.

            You may now continue running your script or Notebook.
            """

        # In a notebook the user just ran a setup cell that was a no-op and
        # needs telling they can carry on; on a plain CLI run the same text is
        # noise on every run, so it drops to DEBUG where it stays retrievable.
        if _running_in_ipython():
            print(message)
        else:
            logger.debug(message)

        return

    # Before anything imports jax: Colab's preinstalled jax is older than the
    # floor, and the --no-deps install below never upgrades it.
    _ensure_jax_floor()

    # JAX performance tweak, applied only on Colab.
    os.environ["XLA_FLAGS"] = _XLA_FLAGS

    no_gpu = check_jax_using_gpu(log_gpu_warning=False)

    if no_gpu and raise_error_if_not_gpu:
        raise RuntimeError(gpu_error_message)

    # --- Install packages (no deps — Colab ships the scientific stack) ---
    print()
    print(f"Now Installing {project_name} and setting up Colab Environment:")

    if pre_install is not None:
        _PRE_INSTALLERS[pre_install]()

    subprocess.check_call(
        [sys.executable, "-m", "pip", "install", *packages, "--no-deps"]
    )

    _clone_workspace(workspace_repo, workspace_dir, top_package)

    # --- Configure autonerves paths ---
    from autonerves import conf

    os.chdir(workspace_dir)

    conf.instance.push(
        new_path=Path(workspace_dir) / "config",
        output_path=Path(workspace_dir) / "output",
    )

    print(
        f"""
        ***Google Colab Setup Complete, which included:***

        - Installation of {project_name} and other required packages.
        - Cloning of the workspace GitHub repository.
        - Setting up environment variables for JAX for improved performance.
        - Setting the configuration paths to the workspace config and output folders suitable for Colab.
        """
    )


def setup(
    project: str,
    raise_error_if_not_gpu: bool = False,
    workspace_dir: str = None,
) -> None:
    """
    Set up Google Colab for a PyAuto notebook repository.

    Parameters
    ----------
    project
        One of: "autofit", "autogalaxy", "autolens", "autocti", "howtofit",
        "howtogalaxy", "howtolens".
    raise_error_if_not_gpu
        If True, raise instead of continuing when Colab has no GPU / TPU
        runtime enabled.
    workspace_dir
        Where to clone the workspace. Defaults to the project's Colab
        directory (``/content/<workspace>``); overridden by CI environments
        that simulate the Colab bootstrap (e.g. PyAutoHeart's verify_install
        check F), where ``/content`` is not writable.
    """
    try:
        spec = _PROJECTS[project]
    except KeyError:
        raise KeyError(
            f"Unknown Colab project '{project}'. Choose from: {sorted(_PROJECTS)}"
        )

    _colab_setup(
        project_name=spec["project_name"],
        workspace_repo=spec["workspace_repo"],
        workspace_dir=workspace_dir or spec["workspace_dir"],
        packages=spec["packages"],
        top_package=spec["top_package"],
        raise_error_if_not_gpu=raise_error_if_not_gpu,
        gpu_error_message=_gpu_error_message(project, spec),
        pre_install=spec.get("pre_install"),
    )


